/** Busca o link do criativo normalizando o nome (CR_29, Cr_29, cr_29 → CR_29, CR_55_v1 → CR_55_V1) */
export function getDriveLink(nome: string): string | null {
  const upper = nome.toUpperCase().replace(/^CR(\d)/, "CR_$1");
  // Tenta match exato primeiro (ex: CR_55_V1)
  if (CRIATIVOS_DRIVE[upper]) return CRIATIVOS_DRIVE[upper];
  // Normaliza número com padding (CR_1 → CR_01)
  const normalized = upper.replace(/^CR_0*(\d+)(.*)$/, (_, n, rest) => `CR_${n.padStart(2, "0")}${rest}`);
  return CRIATIVOS_DRIVE[normalized] || null;
}
